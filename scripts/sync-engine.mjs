// Copies the pure game engine from the server repository so the client scores
// moves with exactly the same rules. Run after any engine change on the server.
import { cpSync, existsSync, rmSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const from = fileURLToPath(new URL('../../scrabbleio-server/src/engine/', import.meta.url));
const to = fileURLToPath(new URL('../src/engine/', import.meta.url));

if (!existsSync(from)) {
  console.error(`Engine not found at ${from} (the server repository must sit next to the client).`);
  process.exit(1);
}
rmSync(to, { recursive: true, force: true });
cpSync(from, to, { recursive: true });
const banner = '// GENERATED by scripts/sync-engine.mjs from scrabbleio-server/src/engine — do not edit here.\n';
for (const f of readdirSync(to)) {
  const p = to + f;
  writeFileSync(p, banner + readFileSync(p, 'utf8'));
}
console.log(`Engine synced to ${to}`);
